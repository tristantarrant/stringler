#!/usr/bin/env python3
"""
Generate plugins/<Name>/Presets.hpp from presets/<id>.json.

This is the Dataforte rule for plugin presets: the names, values, defaults
and metadata live in one JSON file; this script validates them against the
declared ranges and emits the C++ table that the DPF wrapper exposes as
programs. DPF then exports those programs to the LV2 manifest/presets.ttl
and shows them in VST3/CLAP hosts, so one data file feeds every format.

The "parameters" array in the JSON must list the parameters in the same
order as the Parameters enum in DistrhoPluginInfo.h. Program 0 must equal
"defaults" (DPF convention: program 0 is the plugin's initial state).

Usage: tools/gen_presets.py presets/<id>.json plugins/<Name>/Presets.hpp
"""

import json
import os
import sys


def fail(msg):
    sys.exit("gen_presets: " + msg)


def main():
    if len(sys.argv) != 3:
        fail("usage: gen_presets.py <presets.json> <out.hpp>")
    src, out = sys.argv[1], sys.argv[2]

    with open(src) as f:
        data = json.load(f)

    params = data.get("parameters")
    if not isinstance(params, list) or not params:
        fail("'parameters' must be a non-empty list")
    if len(set(params)) != len(params):
        fail("duplicate parameter names")
    for k in params:
        if not isinstance(k, str) or not k:
            fail("parameter names must be non-empty strings")

    ranges = data.get("ranges", {})
    for k in params:
        if k not in ranges or len(ranges[k]) != 2:
            fail("missing or malformed range for %r" % k)
        lo, hi = ranges[k]
        if not lo < hi:
            fail("range for %r must be lo < hi" % k)

    integers = set(data.get("integers", []))
    for k in integers:
        if k not in params:
            fail("integer %r is not a parameter" % k)

    presets = data.get("presets", [])
    if not presets:
        fail("no presets")

    def values(entry, where):
        v = entry.get("values", {})
        out = []
        for k in params:
            if k not in v:
                fail("%s: missing %r" % (where, k))
            x = float(v[k])
            lo, hi = ranges[k]
            if not (lo <= x <= hi):
                fail("%s: %s=%g outside [%g, %g]" % (where, k, x, lo, hi))
            if k in integers and x != round(x):
                fail("%s: %s must be an integer" % (where, k))
            out.append(x)
        return out

    defaults = data.get("defaults", {})
    dv = values({"values": defaults}, "defaults")

    entries = []
    for i, p in enumerate(presets):
        name = p.get("name", "").strip()
        if not name:
            fail("preset %d has no name" % i)
        entries.append((name, values(p, "preset %d (%s)" % (i, name))))

    # DPF program 0 is the initial state: require it to be the defaults.
    if any(abs(a - b) > 1e-6 for a, b in zip(dv, entries[0][1])):
        fail("program 0 must equal defaults (edit the first preset or defaults)")

    n = len(params)

    def f(x):
        # stable, readable float literal (always with a decimal point)
        s = ("%.6f" % x).rstrip("0").rstrip(".")
        if s in ("", "-0"):
            s = "0"
        if "." not in s:
            s += ".0"
        return s + "f"

    def body(name, vals):
        return '{ "%s", { %s } }' % (name.replace('"', '\\"'),
                                     ", ".join(f(x) for x in vals))

    lines = [
        "/*",
        " * Preset table and parameter defaults.",
        " *",
        " * GENERATED by tools/gen_presets.py from %s -- do not edit by hand." % src,
        " * Edit the JSON and run `make presets`.",
        " *",
        " * Parameter order (must match the Parameters enum in",
        " * DistrhoPluginInfo.h): %s" % ", ".join(params),
        " *",
        " * Copyright (C) 2026 Dataforte",
        " * SPDX-License-Identifier: GPL-2.0-or-later",
        " */",
        "",
        "#pragma once",
        "",
        "namespace preset_data {",
        "",
        "constexpr unsigned kParamCount = %d;" % n,
        "",
        "struct Entry {",
        "    const char* name;",
        "    float value[kParamCount];   // in the DistrhoPluginInfo.h order",
        "};",
        "",
        "constexpr Entry kDefaults = " + body("Default", dv).strip() + ";",
        "",
        "constexpr Entry kEntries[] = {",
    ]
    for name, vals in entries:
        lines.append("    " + body(name, vals) + ",")
    lines += [
        "};",
        "constexpr unsigned kCount = sizeof(kEntries) / sizeof(kEntries[0]);",
        "",
        "} // namespace preset_data",
        "",
    ]

    with open(out, "w") as fh:
        fh.write("\n".join(lines))
    print("wrote %s (%d presets, %d parameters)" % (out, len(entries), n))


if __name__ == "__main__":
    main()
